#!/usr/bin/env sh
set -eu

cd "$(dirname "$0")/.."

asm() { ./build/stages/asm-core-stage-1; }
failed=0

run_test() {
  out=$(printf '%b\n' "$1" | asm) || { err check "$1: asm-core failed"; failed=1; return 0; }
  want=$(printf '%b' "$2")
  [ "$out" = "$want" ] || { err check "$1: expected '$2' got '$out'"; failed=1; }
}

run_test 'mov rax rbx' '48 89 C3'
run_test 'mov eax ebx' '89 C3'
run_test 'mov ax bx' '66 89 C3'
run_test 'mov al bl' '40 88 C3'
run_test 'mov r8 r9' '4D 89 C1'
run_test 'mov r8d r9d' '45 89 C1'
run_test 'mov r8w r9w' '66 45 89 C1'
run_test 'mov r8b r9b' '45 88 C1'
run_test 'mov spl dil' '40 88 E7'
run_test 'mov rax rbx\nret' '48 89 C3\nC3'

run_test 'mov rax [rbx]' '48 89 83 00 00 00 00'
run_test 'mov eax [rbx]' '89 83 00 00 00 00'
run_test 'mov ax [rbx]' '66 89 83 00 00 00 00'
run_test 'mov al [rbx]' '40 88 83 00 00 00 00'
run_test 'mov sil [rbx]' '40 88 B3 00 00 00 00'
run_test 'mov rax [rbx+i8]' '48 89 83 08 00 00 00'
run_test 'mov rax [rbp]' '48 89 85 00 00 00 00'
run_test 'mov rax [r13]' '49 89 85 00 00 00 00'
run_test 'mov r8 [r9+i8]' '4D 89 81 08 00 00 00'

run_test 'mov [rbx] rax' '48 8B 83 00 00 00 00'
run_test 'mov [rbx] eax' '8B 83 00 00 00 00'
run_test 'mov [rbx] ax' '66 8B 83 00 00 00 00'
run_test 'mov [rbx] al' '40 8A 83 00 00 00 00'
run_test 'mov [rbx+0x10] rax' '48 8B 83 10 00 00 00'
run_test 'mov [r9+i8] r8' '4D 8B 81 08 00 00 00'

run_test 'let rax i1' '48 B8 01 00 00 00 00 00 00 00'
run_test 'let rbx i123' '48 BB 7B 00 00 00 00 00 00 00'
run_test 'let eax i1' 'B8 01 00 00 00'
run_test 'let ax i1' '66 B8 01 00'
run_test 'let al i1' '40 B0 01'
run_test 'let r8 i1' '49 B8 01 00 00 00 00 00 00 00'
run_test 'let r9d i1' '41 B9 01 00 00 00'
run_test 'let r10w i1' '66 41 BA 01 00'
run_test 'let r11b i1' '41 B3 01'
run_test 'let sil i1' '40 B6 01'
run_test 'let rax 0x1122334455667788' '48 B8 88 77 66 55 44 33 22 11'
run_test 'let eax 0x1234' 'B8 34 12 00 00'
run_test 'let ax ABCD' '66 B8 AB CD'
run_test 'let eax "abcd"' 'B8 61 62 63 64'
run_test 'let al "a"' '40 B0 61'
run_test ':a\nlet eax :a' '\nB8 00 00 40 00'

run_test 'push rax' '50'
run_test 'push rbx' '53'
run_test 'push r8' '41 50'
run_test 'push r15' '41 57'
run_test 'pop rax' '58'
run_test 'pop rbx' '5B'
run_test 'pop r8' '41 58'
run_test 'pop r15' '41 5F'

run_test 'add rax rbx' '48 01 D8'
run_test 'or rax rbx' '48 09 D8'
run_test 'and rax rbx' '48 21 D8'
run_test 'sub rax rbx' '48 29 D8'
run_test 'xor rax rbx' '48 31 D8'
run_test 'cmp rax rbx' '48 39 D8'
run_test 'add eax ebx' '01 D8'
run_test 'add ax bx' '66 01 D8'
run_test 'add r8 r9' '4D 01 C8'
run_test 'add al bl' '40 00 D8'
run_test 'or al bl' '40 08 D8'
run_test 'and al bl' '40 20 D8'
run_test 'sub al bl' '40 28 D8'
run_test 'xor al bl' '40 30 D8'
run_test 'cmp al bl' '40 38 D8'

run_test 'add eax i1' '81 C0 01 00 00 00'
run_test 'or eax i1' '81 C8 01 00 00 00'
run_test 'and eax i1' '81 E0 01 00 00 00'
run_test 'sub eax i1' '81 E8 01 00 00 00'
run_test 'xor eax i1' '81 F0 01 00 00 00'
run_test 'cmp eax i1' '81 F8 01 00 00 00'
run_test 'cmp ebx 0x12345678' '81 FB 78 56 34 12'
run_test 'add r8d i1' '41 81 C0 01 00 00 00'
run_test 'add ax i1' '66 81 C0 01 00'
run_test 'add al i1' '40 80 C0 01'
run_test 'or al i1' '40 80 C8 01'
run_test 'and al i1' '40 80 E0 01'
run_test 'sub al i1' '40 80 E8 01'
run_test 'xor al i1' '40 80 F0 01'
run_test 'cmp al i1' '40 80 F8 01'
run_test 'add dil i1' '40 80 C7 01'

run_test 'shl rax i3' '48 C1 E0 03'
run_test 'shl eax i3' 'C1 E0 03'
run_test 'shl ax i3' '66 C1 E0 03'
run_test 'shl al i3' '40 C0 E0 03'
run_test 'shl r9 i2' '49 C1 E1 02'

run_test 'jmp :a\n:a' 'E9 00 00 00 00'
run_test 'je :a\n:a' '0F 84 00 00 00 00'
run_test 'jne :a\n:a' '0F 85 00 00 00 00'
run_test 'jb :a\n:a' '0F 82 00 00 00 00'
run_test 'call :a\n:a' 'E8 00 00 00 00'
run_test ':a\njmp :a' '\nE9 FB FF FF FF'
run_test ':a\nje :a' '\n0F 84 FA FF FF FF'
run_test ':a\ncall :a' '\nE8 FB FF FF FF'
run_test 'jmp :a\ndb 01 02\n:a' 'E9 02 00 00 00\n01 02'
run_test 'ret' 'C3'
run_test 'syscall' '0F 05'

run_test 'db 01' '01'
run_test 'db 0102' '01 02'
run_test 'db 01 02' '01 02'
run_test 'db AB' 'AB'
run_test 'db ABCD' 'AB CD'
run_test 'db "abc"' '61 62 63'
run_test 'db "a" "b"' '61 62'
run_test 'db i0' '00'
run_test 'db i1' '01'
run_test 'db i255' 'FF'
run_test 'db i256' '00 01'
run_test 'db i258' '02 01'
run_test 'db 0x1F' '1F'
run_test 'db 0x1234' '34 12'
run_test 'db 1F "a" i1' '1F 61 01'
run_test 'db ab 1f' 'AB 1F'
run_test 'db 0xaB' 'AB'

run_test 'mov rax [rsp]' '48 89 84 24 00 00 00 00'
run_test 'mov rax [rsp+i8]' '48 89 84 24 08 00 00 00'
run_test 'mov [rsp+i8] rax' '48 8B 84 24 08 00 00 00'
run_test 'mov rax [r12]' '49 89 84 24 00 00 00 00'
run_test 'mov [r12+i8] r8' '4D 8B 84 24 08 00 00 00'
run_test 'mov al [rsp]' '40 88 84 24 00 00 00 00'
run_test 'mov rax rsp' '48 89 C4'
run_test 'mov rsp rax' '48 89 E0'
run_test 'add rsp rax' '48 01 C4'
run_test 'mov spl al' '40 88 E0'
run_test 'mov ah bl' '88 E3'
run_test 'mov bl ah' '88 DC'
run_test 'mov ch dh' '88 EE'
run_test 'mov ah bh' '88 E7'
run_test 'let ah i1' 'B4 01'
run_test 'let ch i1' 'B5 01'
run_test 'let dh i1' 'B6 01'
run_test 'let bh i1' 'B7 01'
run_test 'add ah i1' '80 C4 01'
run_test 'cmp dh i1' '80 FE 01'
run_test 'add ch bl' '00 DD'
run_test 'shl ah i3' 'C0 E4 03'
run_test 'mov [rbx] ah' '8A A3 00 00 00 00'
run_test 'mov dh [rbx+i8]' '88 B3 08 00 00 00'

[ "$failed" -eq 0 ] || err-fatal check stage 1
